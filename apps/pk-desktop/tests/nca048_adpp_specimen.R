test_that('Shiny allows explicit analyte order and applies it to every download', {
 f<-adpp_fixture(); d<-rbind(transform(f$data,PCTESTCD='PARENT'),transform(f$data,PCTESTCD='METAB'))
 p<-tempfile();dir.create(p);on.exit(unlink(p,recursive=TRUE),add=TRUE);e<-core$desktop_nca_engine(p)
 input_path<-tempfile(fileext='.csv');on.exit(unlink(input_path),add=TRUE);core$pk_write_csv(d,input_path)
 shiny::testServer(core$desktop_nca_server,args=list(engine=e),{
  session$setInputs(source='FILE',file=list(datapath=input_path,name='input.csv'),id='USUBJID',time='TIME',concentration='CONC',groups=c('STUDYID','PERIOD','TRT','PCTESTCD'),unit_column='UNIT',c0_method='none',auc_method='linear',last_observation=TRUE)
  entries<-c(f$spec$group_roles,list(list(column='PCTESTCD',role='analyte')))
  for(item in entries) do.call(session$setInputs,setNames(list(item$role),paste0('group_role_column_',digest::digest(item$column,algo='sha256',serialize=FALSE))))
  expect_match(output$group_role_controls$html,'検体',fixed=TRUE)
  nca_confirm_displayed(session, input, output)
  session$setInputs(run=1);nca_wait_for_job(e,session);expect_match(output$adpp_order_controls$html,'仮番号の順序',fixed=TRUE)
  session$setInputs(adpp_manual_order=TRUE,adpp_order_column='PCTESTCD',adpp_order_values=c('PARENT','METAB'));session$flushReact()
  got<-pkapp_read_table(output$adpp_csv,format='csv');peak<-unique(got[got$NCAPCD=='CMAX',c('PCTESTCD','PARAMCD')])
  expect_identical(peak$PARAMCD[peak$PCTESTCD=='PARENT'],'CMAX1')
  record<-core$desktop_read(output$adpp_record);expect_identical(unlist(record$analyte_order$values,use.names=FALSE),c('PARENT','METAB'))
  extract<-file.path(p,'export');dir.create(extract);utils::unzip(output$adpp_bundle,exdir=extract)
  zipped<-pkapp_read_table(file.path(extract,'ADPP_CANDIDATE.csv'),format='csv')
  expect_identical(unique(zipped$PARAMCD[zipped$NCAPCD=='CMAX' & zipped$PCTESTCD=='PARENT']),'CMAX1')
  zip_record<-core$desktop_read(file.path(extract,'ADPP_CANDIDATE_RECORD.json'))
  expect_identical(unlist(zip_record$analyte_order$values,use.names=FALSE),c('PARENT','METAB'))
  session$setInputs(adpp_order_values='PARENT');session$flushReact();expect_match(output$adpp_draft_exports$html,'すべて',fixed=TRUE)
 })
})
