test_that('other columns with multiple within-subject values are refused without blocking subject-level groups', {
 f<-adpp_fixture(); d<-rbind(transform(f$data,PCTESTCD='PARENT'),transform(f$data,PCTESTCD='METAB'))
 spec<-f$spec;spec$groups<-c(spec$groups,list('PCTESTCD'))
 spec$group_roles<-c(spec$group_roles,list(list(column='PCTESTCD',role='other')))
 nca<-pkapp_nca(d,spec);expect_error(pkapp_adpp_draft(nca),'PCTESTCD.*複数')
 d$DOSEGRP<-ifelse(d$USUBJID=='STUDY-01-001','LOW','HIGH')
 spec$groups<-c(spec$groups,list('DOSEGRP'));spec$group_roles[[length(spec$group_roles)]]$role<-'analyte'
 spec$group_roles<-c(spec$group_roles,list(list(column='DOSEGRP',role='other')))
 out<-pkapp_adpp_draft(pkapp_nca(d,spec));expect_setequal(unique(out$data$DOSEGRP),c('LOW','HIGH'))
})

test_that('specimen and analyte combinations define distinct parameters and remain traceable', {
 f<-adpp_fixture();d<-do.call(rbind,lapply(c('PARENT','METAB'),function(a) do.call(rbind,lapply(c('PLASMA','URINE'),function(s) transform(f$data,PCTESTCD=a,PPSPEC=s)))))
 spec<-f$spec;spec$groups<-c(spec$groups,list('PCTESTCD','PPSPEC'))
 spec$group_roles<-c(spec$group_roles,list(list(column='PCTESTCD',role='analyte'),list(column='PPSPEC',role='specimen')))
 nca<-pkapp_nca(d,spec); out<-pkapp_adpp_draft(nca)
 peak<-unique(out$data[out$data$NCAPCD=='CMAX',c('PCTESTCD','PPSPEC','PARAMCD','PARAM')])
 expect_equal(nrow(peak),4L);expect_equal(length(unique(peak$PARAMCD)),4L)
 expect_true(all(mapply(function(x,y,p) grepl(x,p,fixed=TRUE)&&grepl(y,p,fixed=TRUE),peak$PCTESTCD,peak$PPSPEC,peak$PARAM)))
 expect_true(all(c('PCTESTCD','PPSPEC') %in% names(out$record$parameter_mapping)))
 ordered<-pkapp_adpp_draft(nca,analyte_order=list(column='PCTESTCD',values=list('PARENT','METAB')))
 p<-unique(ordered$data[ordered$data$NCAPCD=='CMAX',c('PCTESTCD','PARAMCD')])
 expect_setequal(p$PARAMCD[p$PCTESTCD=='PARENT'],c('CMAX1','CMAX2'))
 expect_setequal(p$PARAMCD[p$PCTESTCD=='METAB'],c('CMAX3','CMAX4'))
 expect_identical(out$data$AVAL,nca$data$AVAL);expect_identical(out$data$NCAPSTAT,nca$data$PARAM_STATUS)
 expect_match(out$metadata$REVIEW[out$metadata$VARIABLE=='PPSPEC'],'Specimen',fixed=TRUE)
 specimen_only<-d[d$PCTESTCD=='PARENT',];spec2<-spec;spec2$groups<-Filter(function(x) x!='PCTESTCD',spec2$groups)
 spec2$group_roles<-Filter(function(x) x$column!='PCTESTCD',spec2$group_roles)
 specimen_result<-pkapp_adpp_draft(pkapp_nca(specimen_only,spec2));specimen_peak<-specimen_result$data[specimen_result$data$NCAPCD=='CMAX',]
 expect_equal(length(unique(specimen_peak$PARAMCD)),2L)
 spec$group_roles[[length(spec$group_roles)]]$role<-'other'
 expect_error(pkapp_adpp_draft(pkapp_nca(d,spec)),'PPSPEC.*複数')
})

test_that('user order is complete, stable to row order and recorded in the review package', {
 f<-adpp_fixture();d<-rbind(transform(f$data,PCTESTCD='PARENT'),transform(f$data,PCTESTCD='METAB'))
 spec<-f$spec;spec$groups<-c(spec$groups,list('PCTESTCD'));spec$group_roles<-c(spec$group_roles,list(list(column='PCTESTCD',role='analyte')))
 nca<-pkapp_nca(d,spec);manual<-list(column='PCTESTCD',values=list('PARENT','METAB'))
 out<-pkapp_adpp_draft(nca,analyte_order=manual);peak<-unique(out$data[out$data$NCAPCD=='CMAX',c('PCTESTCD','PARAMCD')])
 expect_identical(peak$PARAMCD[peak$PCTESTCD=='PARENT'],'CMAX1');expect_identical(peak$PARAMCD[peak$PCTESTCD=='METAB'],'CMAX2')
 expect_identical(out$record$analyte_order,manual)
 reversed<-nca;reversed$data<-nca$data[rev(seq_len(nrow(nca$data))),]
 key<-function(x) sort(paste(x$NCAPCD,x$PCTESTCD,x$PARAMCD,sep='|'))
 expect_identical(key(pkapp_adpp_draft(reversed,analyte_order=manual)$data),key(out$data))
 expect_error(pkapp_adpp_draft(nca,analyte_order=list(column='PCTESTCD',values=list('PARENT'))),'すべて')
 expect_error(pkapp_adpp_draft(nca,analyte_order=list(column='PERIOD',values=list('1','2'))),'分析対象物')
 expect_error(pkapp_adpp_draft(nca,analyte_order=list(column='PCTESTCD',values=list('PARENT','PARENT'))),'重複')
 path<-tempfile(fileext='.zip');dir<-tempfile();dir.create(dir);on.exit({unlink(path);unlink(dir,recursive=TRUE)},add=TRUE)
 pkapp_write_adpp_draft(nca,path,analyte_order=manual);utils::unzip(path,exdir=dir)
 record<-jsonlite::fromJSON(file.path(dir,'ADPP_CANDIDATE_RECORD.json'),simplifyVector=FALSE)
 expect_identical(record$analyte_order,manual)
})

