source('apps/pk-desktop/tests/nca051_adpp_suffix.R')
source("apps/pk-desktop/tests/helper_nca_review.R")

test_that('switching methods and replacing suffix files never reuses retained server uploads', {
 f<-adpp_fixture();d<-rbind(transform(f$data,PCTESTCD='PARENT'),transform(f$data,PCTESTCD='METAB'))
 p<-tempfile();dir.create(p);on.exit(unlink(p,recursive=TRUE),add=TRUE);e<-core$desktop_nca_engine(p)
 src<-file.path(p,'input.csv');core$pk_write_csv(d,src)
 shiny::testServer(core$desktop_nca_server,args=list(engine=e),{
  session$setInputs(source='FILE',file=list(datapath=src,name='input.csv'),id='USUBJID',time='TIME',concentration='CONC',groups=c('STUDYID','PERIOD','TRT','PCTESTCD'),unit_column='UNIT',c0_method='none',auc_method='linear',last_observation=TRUE)
  for(item in c(f$spec$group_roles,list(list(column='PCTESTCD',role='analyte')))) do.call(session$setInputs,setNames(list(item$role),paste0('group_role_column_',digest::digest(item$column,algo='sha256',serialize=FALSE))))
  nca_confirm_displayed(session, input, output)
  session$setInputs(run=1);nca_wait_for_job(e,session)
  session$setInputs(adpp_use_mapping=TRUE,adpp_mapping_mode='suffix');session$flushReact()
  sm<-core$pkapp_adpp_suffix_template(result()$value);sm$SUFFIX<-ifelse(sm$PCTESTCD=='PARENT','','M')
  suffix_path<-file.path(p,'suffix.csv');utils::write.csv(sm,suffix_path,row.names=FALSE,na='')
  old_suffix_id<-adpp_mapping_input_id();do.call(session$setInputs,setNames(list(list(datapath=suffix_path,name='suffix.csv')),old_suffix_id));session$flushReact()
  ov<-pkapp_adpp_mapping_template(result()$value)[1,,drop=FALSE];ov$PARAMCD<-'OVERRIDE'
  override_path<-file.path(p,'override.csv');utils::write.csv(ov,override_path,row.names=FALSE,na='')
  old_override_id<-adpp_override_input_id();do.call(session$setInputs,setNames(list(list(datapath=override_path,name='override.csv')),old_override_id));session$flushReact()
  rec<-core$desktop_read(output$adpp_record);expect_identical(rec$parameter_mapping_method,'suffix');expect_false(is.null(rec$parameter_mapping_input_hashes$overrides))
  full<-pkapp_adpp_mapping_template(result()$value);full$PARAMCD<-sprintf('P%03d',seq_len(nrow(full)))
  full_path<-file.path(p,'full.csv');utils::write.csv(full,full_path,row.names=FALSE,na='')
  session$setInputs(adpp_mapping_mode='full');session$flushReact()
  expect_false(identical(old_suffix_id,adpp_mapping_input_id()));expect_null(adpp_mapping_file())
  expect_match(output$adpp_draft_exports$html,'CSVを選択',fixed=TRUE);expect_match(output$adpp_draft_exports$html,'disabled',fixed=TRUE)
  expect_false(grepl('対応表の列は',output$adpp_draft_exports$html,fixed=TRUE))
  expect_false(is.null(input[[old_suffix_id]]))
  old_full_id<-adpp_mapping_input_id();do.call(session$setInputs,setNames(list(list(datapath=full_path,name='full.csv')),old_full_id));session$flushReact()
  rec<-core$desktop_read(output$adpp_record);expect_identical(rec$parameter_mapping_method,'individual')
  session$setInputs(adpp_mapping_mode='suffix');session$flushReact()
  expect_null(adpp_mapping_file());expect_null(adpp_override_file());expect_false(identical(old_suffix_id,adpp_mapping_input_id()))
  expect_false(is.null(input[[old_override_id]]));expect_match(output$adpp_draft_exports$html,'CSVを選択',fixed=TRUE)
  do.call(session$setInputs,setNames(list(list(datapath=suffix_path,name='suffix.csv')),adpp_mapping_input_id()));session$flushReact()
  expect_null(adpp_override_file());rec<-core$desktop_read(output$adpp_record);expect_null(rec$parameter_mapping_input_hashes$overrides)
  override_id<-adpp_override_input_id();do.call(session$setInputs,setNames(list(list(datapath=override_path,name='override.csv')),override_id));session$flushReact()
  expect_false(is.null(adpp_override_file()))
  do.call(session$setInputs,setNames(list(list(datapath=suffix_path,name='suffix-again.csv')),adpp_mapping_input_id()));session$flushReact()
  expect_false(identical(override_id,adpp_override_input_id()));expect_null(adpp_override_file())
  session$setInputs(adpp_mapping_mode='full');session$flushReact();expect_null(adpp_mapping_file());expect_false(identical(old_full_id,adpp_mapping_input_id()))
  expect_match(output$adpp_draft_exports$html,'CSVを選択',fixed=TRUE)
  current_id<-adpp_mapping_input_id();do.call(session$setInputs,setNames(list(list(datapath=full_path,name='full.csv')),current_id));session$flushReact()
  nca_confirm_displayed(session, input, output)
  session$setInputs(run=2);nca_wait_for_job(e,session);session$flushReact()
  expect_false(identical(current_id,adpp_mapping_input_id()));expect_null(adpp_mapping_file())
 })
})
