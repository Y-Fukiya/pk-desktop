 expect_length(diag$missing,1);expect_length(diag$extra,1);expect_match(diag$extra,'␠',fixed=TRUE)
 expect_error(pkapp_adpp_draft(nca,parameter_mapping=m),'不足')
})

test_that('Shiny imports suffixes and overrides and shows local mismatch details', {
 f<-adpp_fixture();d<-rbind(transform(f$data,PCTESTCD='PARENT'),transform(f$data,PCTESTCD='METAB'))
 p<-tempfile();dir.create(p);on.exit(unlink(p,recursive=TRUE),add=TRUE);e<-core$desktop_nca_engine(p)
 input_path<-file.path(p,'input.csv');core$pk_write_csv(d,input_path)
 shiny::testServer(core$desktop_nca_server,args=list(engine=e),{
  session$setInputs(source='FILE',file=list(datapath=input_path,name='input.csv'),id='USUBJID',time='TIME',concentration='CONC',groups=c('STUDYID','PERIOD','TRT','PCTESTCD'),unit_column='UNIT',c0_method='none',auc_method='linear',last_observation=TRUE)
  entries<-c(f$spec$group_roles,list(list(column='PCTESTCD',role='analyte')))
  for(item in entries) do.call(session$setInputs,setNames(list(item$role),paste0('group_role_column_',digest::digest(item$column,algo='sha256',serialize=FALSE))))
  nca_confirm_displayed(session, input, output)
  session$setInputs(run=1);nca_wait_for_job(e,session)
  sm<-utils::read.csv(output$adpp_suffix_template,colClasses='character',check.names=FALSE);sm$SUFFIX<-ifelse(sm$PCTESTCD=='PARENT','P','M')
  suffix_path<-file.path(p,'suffix.csv');utils::write.csv(sm,suffix_path,row.names=FALSE,na='')
  session$setInputs(adpp_use_mapping=TRUE,adpp_mapping_mode='suffix');session$flushReact()
  do.call(session$setInputs,setNames(list(list(datapath=suffix_path,name='suffix.csv')),adpp_mapping_input_id()));session$flushReact()
  got<-pkapp_read_table(output$adpp_csv,format='csv')
  expect_true(all(grepl('[PM]$',got$PARAMCD)));expect_match(output$adpp_draft_exports$html,'プレビュー',fixed=TRUE)
  full<-pkapp_adpp_mapping_template(result()$value);full$PARAMCD<-sprintf('P%03d',seq_len(nrow(full)));full$PCTESTCD[1]<-paste0(full$PCTESTCD[1],' ')
  full_path<-file.path(p,'full.csv');utils::write.csv(full,full_path,row.names=FALSE,na='')
  session$setInputs(adpp_mapping_mode='full');session$flushReact()
  do.call(session$setInputs,setNames(list(list(datapath=full_path,name='full.csv')),adpp_mapping_input_id()));session$flushReact()
  expect_match(output$adpp_draft_exports$html,'不足',fixed=TRUE);expect_match(output$adpp_draft_exports$html,'␠',fixed=TRUE)
  writeBin(c(charToRaw('NCAPCD,PCTESTCD,PARAMCD\nCMAX,'),as.raw(c(130,160)),charToRaw(',CMAXP\n')),full_path)
  do.call(session$setInputs,setNames(list(list(datapath=full_path,name='cp932.csv')),adpp_mapping_input_id()));session$flushReact()
  expect_match(output$adpp_draft_exports$html,'CSV UTF-8',fixed=TRUE);expect_match(output$adpp_draft_exports$html,'disabled',fixed=TRUE)
 })
})

test_that('suffix mapping distinguishes analyte and specimen combinations', {
 f<-adpp_fixture();d<-do.call(rbind,lapply(c('PARENT','METAB'),function(a) do.call(rbind,lapply(c('PLASMA','URINE'),function(s) transform(f$data,PCTESTCD=a,PPSPEC=s)))))
 spec<-f$spec;spec$groups<-c(spec$groups,list('PCTESTCD','PPSPEC'));spec$group_roles<-c(spec$group_roles,list(list(column='PCTESTCD',role='analyte'),list(column='PPSPEC',role='specimen')))
 nca<-pkapp_nca(d,spec);sm<-core$pkapp_adpp_suffix_template(nca)
 expect_equal(nrow(sm),4L);sm$SUFFIX<-paste0(ifelse(sm$PCTESTCD=='PARENT','P','M'),ifelse(sm$PPSPEC=='PLASMA','P','U'))
 mapping<-core$pkapp_adpp_expand_suffix_mapping(nca,sm);out<-pkapp_adpp_draft(nca,parameter_mapping=mapping)
 expect_identical(out$record$parameter_mapping_source,'user_supplied')
 expect_equal(nrow(unique(out$data[c('NCAPCD','PCTESTCD','PPSPEC','PARAMCD')])),nrow(mapping))
 expect_false(anyDuplicated(mapping$PARAMCD)>0)
})
