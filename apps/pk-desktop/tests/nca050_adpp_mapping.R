test_that('UTF-8 mapping files are decoded completely; invalid encodings never produce partial data', {
 p<-tempfile();on.exit(unlink(p),add=TRUE)
 d<-data.frame(NCAPCD='CMAX',PCTESTCD='未変化体',PARAMCD='CMAXP',check.names=FALSE)
 utils::write.csv(d,p,row.names=FALSE,na='',fileEncoding='UTF-8')
 expect_equal(core$desktop_adpp_read_mapping_csv(p),d)
 bytes<-readBin(p,'raw',n=file.info(p)$size);writeBin(c(as.raw(c(239,187,191)),bytes),p)
 expect_equal(core$desktop_adpp_read_mapping_csv(p),d)
 lines<-paste0('NCAPCD,PCTESTCD,PARAMCD\nCMAX,',iconv('未変化体',from='UTF-8',to='CP932'),',CMAXP\n')
 writeBin(charToRaw(lines),p)
 expect_error(core$desktop_adpp_read_mapping_csv(p),'CSV UTF-8')
 writeBin(c(bytes,as.raw(255)),p);expect_error(core$desktop_adpp_read_mapping_csv(p),'UTF-8')
})

test_that('suffixes expand exactly and sparse overrides resolve length issues without silent truncation', {
 f<-adpp_fixture();d<-rbind(transform(f$data,PCTESTCD='PARENT'),transform(f$data,PCTESTCD='METAB'))
 spec<-f$spec;spec$groups<-c(spec$groups,list('PCTESTCD'));spec$group_roles<-c(spec$group_roles,list(list(column='PCTESTCD',role='analyte')))
 nca<-pkapp_nca(d,spec)
 sm<-core$pkapp_adpp_suffix_template(nca);sm$SUFFIX<-ifelse(sm$PCTESTCD=='PARENT','P','M')
 full<-core$pkapp_adpp_expand_suffix_mapping(nca,sm)
 expect_equal(full$PARAMCD,paste0(full$NCAPCD,ifelse(full$PCTESTCD=='PARENT','P','M')))
 out<-pkapp_adpp_draft(nca,parameter_mapping=full)
 expect_setequal(unique(out$data$PARAMCD),full$PARAMCD)
 expect_identical(out$record$parameter_mapping_source,'user_supplied')
 bad<-sm;bad$SUFFIX<-'X';expect_error(core$pkapp_adpp_expand_suffix_mapping(nca,bad),'重複')
 bad<-sm;bad$SUFFIX[1]<-'p';expect_error(core$pkapp_adpp_expand_suffix_mapping(nca,bad),'英大文字')
 expect_error(core$pkapp_adpp_expand_suffix_mapping(nca,sm[-1,,drop=FALSE]),'不足')
 bad<-full;bad$PARAMCD[1]<-tolower(bad$PARAMCD[1]);expect_error(pkapp_adpp_draft(nca,parameter_mapping=bad),'英大文字')
 long<-nca;long$data$PARAMCD[long$data$PARAMCD=='CMAX']<-'ABCDEFGH'
 expect_error(core$pkapp_adpp_expand_suffix_mapping(long,sm),'8文字')
 template<-core$pkapp_adpp_suffix_override_template(long,sm);expect_equal(nrow(template),2L);expect_true(all(template$PARAMCD==''))
 overrides<-pkapp_adpp_mapping_template(long);overrides<-overrides[overrides$NCAPCD=='ABCDEFGH',,drop=FALSE];overrides$PARAMCD<-c('SPECIAL1','SPECIAL2')
 expanded<-core$pkapp_adpp_expand_suffix_mapping(long,sm,overrides)
 expect_setequal(expanded$PARAMCD[expanded$NCAPCD=='ABCDEFGH'],c('SPECIAL1','SPECIAL2'))
 bad<-overrides;bad$NCAPCD[1]<-'UNKNOWN';expect_error(core$pkapp_adpp_expand_suffix_mapping(long,sm,bad),'余分')
 bad<-rbind(overrides,overrides[1,]);expect_error(core$pkapp_adpp_expand_suffix_mapping(long,sm,bad),'重複')
})

test_that('local diagnostics identify missing and unexpected combinations and expose whitespace', {
