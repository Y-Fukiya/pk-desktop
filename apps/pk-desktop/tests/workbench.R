test_that("PK draft preview reports rule counts without changing applied data or save state", {
  d <- data.frame(ID = "001", SAMPLE = c("2026-11-09T08:45", "2026-11-09T09:30", "2026-11-09T10:00", "2026-11-09T11:00", "2026-11-09T13:00"),
    DOSE = "2026-11-09T09:00", CONC = c("<0.2", "3", "8", "4", "<0.2"), BLQ = c(1,0,0,0,1))
  file <- tempfile(fileext = ".csv"); core$pk_write_csv(d, file)
  project <- tempfile(); dir.create(project)
  engine <- core$desktop_nca_engine(project)
  shiny::testServer(core$desktop_workbench_server, args = list(engine = engine), {
    session$setInputs(source = "FILE", mode = "catalog", op = "", file = list(name = "draft.csv", datapath = file), load_source = 1)
    original <- base()
    session$setInputs(mode = "prepare", op = "elapsed_time", sample_column = "SAMPLE", dose_column = "DOSE",
      utc_offset = "+09:00", elapsed_output = "NCA_TIME_H", sample_datetime_type = "iso", dose_datetime_type = "iso", invalid_datetime = "missing")
    expect_equal(draft_preview()$data$NCA_TIME_H, c(-.25,.5,1,2,4))
    expect_identical(result()$data, original)
    expect_length(steps(), 0)
    expect_null(receipt())
    session$setInputs(apply_step = 1)
    expect_null(draft_preview())
    expect_match(output$notice_ui$html, "適用しました")
    applied <- result()$data
    session$setInputs(op = "blq_rules", blq_mode = "positional", profile_columns = "ID", blq_concentration = "CONC",
      prep_blq_column = "BLQ", blq_time = "NCA_TIME_H", prep_mdv_column = "", predose_column = "", zero_time = "pre",
      prep_time_origin = 0, prep_flag_convention = "strict", pre_rule = "zero", first_rule = "zero",
      middle_rule = "exclude", last_rule = "half_lloq", all_blq_rule = "exclude", lloq_source = "constant", lloq_value = .2)
    expect_equal(output$pre_rule_count, "1 行")
    expect_equal(output$last_rule_count, "1 行")
    expect_equal(draft_preview()$data$NCA_CONC, c(0,3,8,4,.1))
    expect_identical(result()$data, applied)
    expect_length(steps(), 1)
    expect_null(output$notice_ui)
    expect_match(output$state_ui$html, "未適用の変更あり")
    session$setInputs(apply_step = 2)
    expect_equal(result()$data$NCA_CONC, c(0,3,8,4,.1))
    expect_false(dirty())
    session$setInputs(lloq_value = .4)
    expect_true(dirty())
    expect_equal(result()$data$NCA_CONC[5], .1)
    session$setInputs(discard_draft = 1, op = "")
    expect_false(dirty())
    expect_equal(result()$data$NCA_CONC[5], .1)
  })
  html <- as.character(core$desktop_workbench_ui("w"))
  expect_equal(lengths(regmatches(html, gregexpr('id="w-apply_step"', html, fixed = TRUE))), 1)
  expect_equal(lengths(regmatches(html, gregexpr('id="w-first_rule"', html, fixed = TRUE))), 1)
})

test_that("workspace stages F375 then saves and replays an identical joined snapshot", {
  project <- pkapp_open(tempfile("workbench-")); withr::defer(pkapp_close(project))
  engine <- project$engine; original <- engine$data
  shiny::testServer(core$desktop_workbench_server, args = list(engine = engine), {
    session$setInputs(source = "ADNCA", mode = "prepare", op = "", save_name = "女性の濃度")
    expect_equal(nrow(result()$data), 750)
    session$setInputs(op = "filter", column = "SEX", operator = "eq", value = "F")
    expect_true(dirty()); expect_equal(nrow(result()$data), 750)
    expect_match(output$save_actions$html, 'disabled="disabled"')
    expect_error(output$csv, "未適用")
    session$setInputs(mode = "catalog")
    expect_identical(active_mode(), "prepare")
    expect_true(dirty()); expect_identical(input$value, "F")
    expect_match(output$state_ui$html, "未適用の変更あり")
    expect_false(grepl("未適用の変更あり", output$sidebar_status$html, fixed = TRUE))
    session$setInputs(mode = "join")
    expect_identical(active_mode(), "prepare")
    expect_match(notice()$message, "未適用の変更があります")
    session$setInputs(mode = "prepare")
    session$setInputs(save_result = 1)
    expect_length(core$desktop_tables(engine), 0)
    session$setInputs(apply_step = 1)
    expect_equal(dim(result()$data), c(375, 33)); expect_false(dirty())
    session$setInputs(op = "", save_result = 2)
    saved_prep <- receipt()$id
    expect_identical(pkapp_replay(core$desktop_table_path(engine, saved_prep))$data, result()$data)
    session$setInputs(mode = "join", right_source = "ADPP", right_param = "CMAXSS", keys = c("STUDYID", "USUBJID"),
      join_columns = c("PARAMCD", "AVAL", "AVALU"), method = "left")
    expect_true(dirty()); expect_equal(ncol(result()$data), 33)
    session$setInputs(apply_join = 1)
    expect_false(dirty()); expect_equal(dim(result()$data), c(375, 36))
    expect_equal(unname(result()$counts), c(375, 50, 375, 0, 375))
    expected <- pkapp_merge(pkapp_prepare(engine$data$ADNCA, list(list(op = "filter", column = "SEX", operator = "eq", values = list("F"))))$data,
      engine$data$ADPP[engine$data$ADPP$PARAMCD == "CMAXSS", ], c("STUDYID", "USUBJID"), c("PARAMCD", "AVAL", "AVALU"), "left", "ADPP")$data
    expect_identical(result()$data, expected)
    expect_length(result()$recipe$left_steps, 1)
    expect_identical(result()$recipe$right_param, "CMAXSS")
    expect_equal(nrow(result()$inputs$left_source), 750)
    expect_equal(nrow(result()$inputs$right_source), 900)
    misleading <- result()$inputs
    misleading$left <- misleading$left[FALSE, , drop = FALSE]
    misleading$right <- misleading$right[FALSE, , drop = FALSE]
    expect_identical(core$desktop_recipe_run(misleading, result()$recipe)$data, expected)
    session$setInputs(save_name = "女性の結合表", save_result = 3)
    saved_join <- receipt()$id
    expect_length(core$desktop_tables(engine), 2)
    expect_identical(pkapp_replay(core$desktop_table_path(engine, saved_join))$data, expected)
    downloaded <- core$pk_csv(output$csv)
    expect_equal(nrow(downloaded), 375)
    expect_equal(as.numeric(downloaded$ADPP_AVAL), expected$ADPP_AVAL, tolerance = 1e-14)
    session$setInputs(right_param = "__ALL__")
    expect_true(dirty())
    session$setInputs(mode = "catalog")
    expect_identical(active_mode(), "join"); expect_true(dirty())
    expect_equal(nrow(result()$data), 375)
    session$setInputs(mode = "join")
    expect_gt(diagnostics()$counts$duplicate_right_rows, 0)
    session$setInputs(save_result = 4, apply_join = 2)
    expect_equal(result()$data, expected); expect_length(core$desktop_tables(engine), 2)
    expect_match(notice()$message, "重複")
    session$setInputs(discard_draft = 1, right_param = "CMAXSS", mode = "prepare")
    expect_false(dirty())
    session$setInputs(source = saved_prep, load_source = 1)
    expect_equal(nrow(base()), 375)
    expect_length(steps(), 0)
    session$setInputs(op = "filter", column = "TIME_H", operator = "ge", value = "144", apply_step = 2)
    expect_lt(nrow(result()$data), 375)
    expect_equal(nrow(core$desktop_table_get(engine, saved_prep)), 375)
  })
  expect_identical(engine$data, original)
})

test_that("workspace edit cancel, atomic dependency errors, delete and undo preserve valid results", {
  project <- pkapp_open(tempfile("workbench-edit-")); withr::defer(pkapp_close(project))
  engine <- project$engine
  shiny::testServer(core$desktop_workbench_server, args = list(engine = engine), {
    session$setInputs(mode = "prepare", op = "")
    session$setInputs(op = "filter", column = "SEX", operator = "eq", value = "F", apply_step = 1)
    session$setInputs(op = "", edit_step_index = "1", edit_step = 1)
    expect_equal(editing(), 1L); expect_true(dirty())
    session$setInputs(op = "filter", column = "SEX", operator = "eq", value = "M")
    expect_equal(unique(result()$data$SEX), "F")
    session$setInputs(discard_draft = 1, op = "")
    expect_null(editing()); expect_false(dirty()); expect_equal(unique(result()$data$SEX), "F")
    session$setInputs(edit_step = 2)
    session$setInputs(op = "filter", column = "SEX", operator = "eq", value = "M", apply_step = 2)
    expect_equal(unique(result()$data$SEX), "M"); expect_length(steps(), 1)
    session$setInputs(op = "", undo_step = 1)
    expect_equal(unique(result()$data$SEX), "F")
    session$setInputs(op = "rename", column = "SEX", new_name = "GENDER", apply_step = 3)
    session$setInputs(op = "filter", column = "GENDER", operator = "eq", value = "F", apply_step = 4)
    session$setInputs(op = "", edit_step_index = "2", remove_step = 1)
    expect_length(steps(), 3)
    expect_true("GENDER" %in% names(result()$data))
    expect_match(notice()$message, "列がありません")
    session$setInputs(edit_step_index = "3", remove_step = 2)
    expect_length(steps(), 2)
    session$setInputs(undo_step = 2)
    expect_length(steps(), 3)
    session$setInputs(op = "filter", column = "GENDER", operator = "eq", value = "never", apply_step = 5)
    expect_equal(nrow(result()$data), 0)
    session$setInputs(op = "", save_name = "empty checked", save_result = 1)
    expect_equal(nrow(core$desktop_table_get(engine, receipt()$id)), 0)
  })
})

test_that("saved ADPP retains PARAMCD controls and failed files preserve current table", {
  project <- pkapp_open(tempfile("workbench-source-")); withr::defer(pkapp_close(project))
  engine <- project$engine
  saved <- pkapp_save_preparation(project, engine$data$ADPP, list(), "Saved ADPP")
  path <- tempfile(fileext = ".csv")
  core$pk_write_csv(data.frame(ID = c("001", "002"), X = c("x", "y")), path)
  shiny::testServer(core$desktop_workbench_server, args = list(engine = engine), {
    session$setInputs(mode = "prepare", op = "", right_source = saved$id, right_param = "CMAXSS")
    expect_match(output$right_param_ui$html, "CMAXSS")
    session$setInputs(mode = "join", keys = c("STUDYID", "USUBJID"), join_columns = c("PARAMCD", "AVAL"), method = "left", apply_join = 1)
    expect_equal(nrow(result()$data), 750)
    expect_equal(result()$counts[["right"]], 50)
    session$setInputs(discard_draft = 1, mode = "prepare", source = "FILE", file = list(datapath = path, name = "input.csv"), load_source = 1)
    expect_equal(nrow(base()), 750) # unsaved work requires an explicit switch
    session$setInputs(confirm_source = 1)
    expect_identical(base()$ID, c("001", "002"))
    expect_length(steps(), 0)
    bad <- tempfile(fileext = ".rds"); saveRDS(list(x = "invalid"), bad)
    session$setInputs(file = list(datapath = bad, name = "bad.rds"), load_source = 2)
    expect_identical(base()$ID, c("001", "002"))
    expect_match(notice()$message, "列名")
  })
})

test_that("uploaded join keys and missing-key diagnostics remain replayable", {
  project <- pkapp_open(tempfile("workbench-keys-")); withr::defer(pkapp_close(project))
  engine <- project$engine
  fixture <- data.frame(ID = c("001", "002"), KEY = c(1, 2), AVAL = c(1.1, 2.2))
  saved <- pkapp_save_preparation(project, fixture, list(), "numeric keys")
  path <- tempfile(fileext = ".csv")
  core$pk_write_csv(data.frame(ID = c("001", "002"), KEY = c("1", "2"), LABEL = c("A", "B")), path)
  shiny::testServer(core$desktop_workbench_server, args = list(engine = engine), {
    session$setInputs(mode = "prepare", op = "", source = saved$id, load_source = 1)
    session$setInputs(mode = "join", right_source = "FILE", right_file = list(datapath = path, name = "lookup.csv"),
      keys = c("ID", "KEY"), join_columns = "LABEL", method = "left", apply_join = 1)
    expect_equal(result()$data$LABEL, c("A", "B"))
    expect_true(result()$recipe$right_csv_keys)
    expect_false(result()$recipe$left_csv_keys)
    expect_identical(result()$inputs$right_source$KEY, c("1", "2"))
    expect_identical(result()$inputs$right$KEY, c(1, 2))
    expect_identical(core$desktop_recipe_run(result()$inputs, result()$recipe)$data, result()$data)
    session$setInputs(save_name = "uploaded lookup", save_result = 1)
    expect_identical(pkapp_replay(core$desktop_table_path(engine, receipt()$id))$data, result()$data)
    missing <- tempfile(fileext = ".csv")
    core$pk_write_csv(data.frame(ID = c("001", NA), KEY = c("1", "2"), LABEL = c("A", "B")), missing)
    session$setInputs(right_file = list(datapath = missing, name = "missing.csv"), apply_join = 2)
    expect_true(dirty()); expect_equal(diagnostics()$counts$missing_right, 1)
    expect_match(notice()$message, "欠測|空欄")
    expect_equal(result()$data$LABEL, c("A", "B"))
    session$setInputs(save_result = 2)
    expect_length(core$desktop_tables(engine), 2)
    session$setInputs(discard_draft = 1, mode = "prepare")
    expect_false(dirty())
    expect_identical(active_right_file()$datapath, path)
    session$setInputs(mode = "join")
    expect_false(dirty())
    expect_equal(diagnostics()$counts$missing_right, 0)
  })
})
