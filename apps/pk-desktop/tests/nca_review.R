source("apps/pk-desktop/pkapp.R")
library(testthat)
core <- environment(pkapp_open)
review_spec <- list(id = "ID", time = "TIME", concentration = "CONC", concentration_unit = "ng/mL", auc_method = "linear")

test_that("real XPT dates survive import and SAS clocks require explicit interpretation", {
  original <- data.frame(ID = "001", ADT = as.Date("2026-11-09"),
    SAMPLE = as.POSIXct("2026-11-09 10:00:00", tz = "Asia/Tokyo") + c(0, 3600),
    DOSE = "2026-11-09T09:00:00+09:00")
  path <- tempfile(fileext = ".xpt")
  haven::write_xpt(original, path)
  imported <- pkapp_read_table(path)
  expect_s3_class(imported$ADT, "Date")
  expect_s3_class(imported$SAMPLE, "POSIXct")
  step <- list(op = "elapsed_time", sample_column = "SAMPLE", dose_column = "DOSE", utc_offset = "+09:00")
  ambiguous <- pkapp_prepare(imported, list(step))
  expect_true(all(is.na(ambiguous$data$NCA_TIME_H)))
  expect_true(all(ambiguous$trace[[1]]$rows$SAMPLE_REASON == "sas_datetime_requires_clock_mode"))
  local_clock <- pkapp_prepare(imported, list(modifyList(step, list(sample_datetime_type = "sas_seconds"))))
  expect_equal(local_clock$data$NCA_TIME_H, c(1, 2))
  expect_true(all(local_clock$trace[[1]]$rows$SAMPLE_OFFSET_ASSUMED))
  expect_true(all(local_clock$trace[[1]]$rows$SAMPLE_TYPE == "SAS_DATETIME"))
  expect_identical(local_clock$data[names(imported)], imported)
  haven::write_xpt(original, path, adjust_tz = FALSE)
  utc <- pkapp_prepare(pkapp_read_table(path), list(modifyList(step, list(sample_datetime_type = "unix_seconds"))))
  expect_equal(utc$data$NCA_TIME_H, c(1, 2))
  expect_false(any(utc$trace[[1]]$rows$SAMPLE_OFFSET_ASSUMED))
  absolute <- pkapp_prepare(original, list(step))
  expect_equal(absolute$data$NCA_TIME_H, c(1, 2))
  expect_false(any(absolute$trace[[1]]$rows$SAMPLE_OFFSET_ASSUMED))
  date_only <- pkapp_prepare(imported, list(modifyList(step, list(sample_column = "ADT"))))
  expect_true(all(is.na(date_only$data$NCA_TIME_H)))
  expect_true(all(date_only$trace[[1]]$rows$SAMPLE_REASON == "invalid_format"))
  for (sas_format in c("E8601DT19.", "B8601DT19.")) {
    formatted <- original
    attr(formatted$SAMPLE, "format.sas") <- sas_format
    haven::write_xpt(formatted, path)
    loaded <- pkapp_read_table(path)
    expect_s3_class(loaded$SAMPLE, "POSIXct")
    unspecified <- pkapp_prepare(loaded, list(step))
    expect_true(all(is.na(unspecified$data$NCA_TIME_H)))
    explicit <- pkapp_prepare(loaded, list(modifyList(step, list(sample_datetime_type = "sas_seconds"))))
    expect_equal(explicit$data$NCA_TIME_H, c(1, 2))
    expect_true(all(explicit$trace[[1]]$rows$SAMPLE_OFFSET_ASSUMED))
  }
  unlink(path)
})

test_that("AUC row-use flags describe a successful calculation rather than candidate points", {
  input <- data.frame(ID = "001", TIME = c(.5, 1, 2), CONC = c(0, 8, 4), BLQ = c(1, 0, 0))
  s <- modifyList(review_spec, list(blq_column = "BLQ", blq = "as_recorded", include_aucproc = TRUE))
  missing <- pkapp_nca(input, s)
  expect_true(all(is.na(missing$data$AVAL[missing$data$PARAMCD %in% c("AUCLST", "AUCPROC")])))
  expect_false(any(missing$trace$rows$USE_AUC))
  expect_false(any(missing$trace$rows$USE_AUCPROC))
  expect_equal(missing$trace$rows$STATUS[1], "auc_not_calculated")
  expect_match(missing$trace$rows$REASON[1], "Missing concentration")
  expect_equal(missing$counts[["used"]], 2)
  calculated <- pkapp_nca(input, modifyList(s, list(c0_method = "zero")))
  expect_true(all(calculated$trace$rows$USE_AUC))
  expect_true(all(calculated$trace$rows$USE_AUCPROC))
  partial <- pkapp_nca(input, modifyList(s, list(start = .5)))
  expect_true(is.na(partial$data$AVAL[partial$data$PARAMCD == "AUCLST"]))
  expect_true(is.finite(partial$data$AVAL[partial$data$PARAMCD == "AUCPART"]))
  expect_true(all(partial$trace$rows$USE_AUC))
})

test_that("unused terminal BLQ cannot rescue a one-observation profile", {
  one <- data.frame(ID = "001", TIME = 1, CONC = 4, BLQ = 0)
  extra <- rbind(one, data.frame(ID = "001", TIME = 2, CONC = .1, BLQ = 1))
  s <- modifyList(review_spec, list(blq_column = "BLQ", blq = "as_recorded", c0_method = "zero"))
  for (input in list(one, extra)) {
    for (include_processed in c(FALSE, TRUE)) {
      result <- pkapp_nca(input, modifyList(s, list(include_aucproc = include_processed)))
      expect_true(all(result$data$PROFILE_STATUS == "partial"))
      expect_equal(result$data$AVAL[1:2], c(4, 1))
      expect_true(all(is.na(result$data$AVAL[-c(1, 2)])))
      expect_false(any(result$trace$rows$USE_AUC | result$trace$rows$USE_AUCPROC))
      expect_match(result$data$NCA_EXCLUDE[result$data$PARAMCD == "AUCLST"], "Fewer than two")
    }
  }
  leading <- rbind(data.frame(ID = "001", TIME = 0, CONC = 0, BLQ = 1), one)
  result <- pkapp_nca(leading, s)
  expect_equal(result$data$AVAL[result$data$PARAMCD == "AUCLST"], 2)
  expect_true(all(result$data$PROFILE_STATUS == "ok"))
  predose <- rbind(data.frame(ID = "001", TIME = -.25, CONC = 2, BLQ = 0), one)
  result <- pkapp_nca(predose, modifyList(s, list(c0_method = "predose", predose_window_h = .5)))
  expect_equal(result$data$AVAL[result$data$PARAMCD == "AUCLST"], 3)
  expect_true(all(result$data$PROFILE_STATUS == "ok"))
})
