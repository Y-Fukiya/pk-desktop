source("apps/pk-desktop/pkapp.R")
library(testthat)
core <- environment(pkapp_open)
fixture <- data.frame(STUDYID = "S", USUBJID = c("001", "010", "099", "101"),
  SEX = c("F", "M", "F", "M"), AVAL = c(1, 2, 3, 4))
file <- tempfile(fileext = ".csv"); core$pk_write_csv(fixture, file)
html <- function(x) if (is.list(x)) x$html else as.character(x)

project <- pkapp_open(tempfile("preparation-ux-"))
engine <- project$engine

test_that("no input is explicit and native buttons and server guard prevent actions", {
  shiny::testServer(core$desktop_prepare_server, args = list(engine = engine), {
    session$setInputs(source = "FILE")
    expect_false(valid_input()); expect_null(original()); expect_length(steps(), 0)
    expect_match(html(output$result_panel), "データを選択してください")
    expect_match(html(output$add_action), 'disabled="disabled"')
    expect_match(html(output$publish_action), 'disabled="disabled"')
    session$setInputs(op = "filter", column = "SEX", operator = "eq", value = "F", add = 1, name = "Blocked", publish = 1)
    expect_length(core$desktop_tables(engine), 0)
    expect_length(steps(), 0)
  })
})

test_that("applied conditions are readable and save status follows the current result", {
  shiny::testServer(core$desktop_prepare_server, args = list(engine = engine), {
    session$setInputs(source = "FILE", file = list(datapath = file, name = "subjects.csv"))
    expect_true(valid_input())
    expect_false(grepl('disabled="disabled"', html(output$publish_action)))
    session$setInputs(op = "filter", column = "SEX", operator = "eq", value = "F", add = 1)
    expect_identical(result()$data$USUBJID, c("001", "099"))
    expect_match(html(output$condition_list), "SEX が「F」の行を残す", fixed = TRUE)
    expect_match(html(output$condition_list), "4 行 → 2 行", fixed = TRUE)
    session$setInputs(name = "女性データ", publish = 1)
    expect_match(notice(), "Module → データ結合", fixed = TRUE)
    expect_identical(saved_state()$name, "女性データ")
    expect_identical(core$desktop_table_get(engine, saved_state()$id)$USUBJID, c("001", "099"))
    session$setInputs(reset = 1)
    expect_null(saved_state()); expect_length(steps(), 0)
    expect_equal(nrow(result()$data), 4)
    expect_match(notice(), "リセット")
    expect_match(html(output$save_status), "未保存")
    session$setInputs(column = "UNKNOWN", add = 2)
    expect_equal(nrow(result()$data), 4)
    expect_length(steps(), 0)
    expect_identical(notice_tone(), "error")
    expect_match(notice(), "表示中の結果は変更していません")
    session$setInputs(column = "SEX", value = "NONE", add = 3)
    expect_equal(nrow(result()$data), 0)
    expect_match(html(output$zero_result), "条件に一致する行はありません")
    expect_true(valid_input())
    session$setInputs(name = "Empty result", publish = 2)
    expect_equal(nrow(core$desktop_table_get(engine, saved_state()$id)), 0)
  })
})

test_that("changing to an unselected or invalid source clears old data, steps and saved status", {
  shiny::testServer(core$desktop_prepare_server, args = list(engine = engine), {
    session$setInputs(source = "ADNCA")
    session$setInputs(op = "filter", column = "SEX", operator = "eq", value = "F", add = 1)
    session$setInputs(name = "Before switch", publish = 1)
    expect_true(valid_input()); expect_length(steps(), 1); expect_false(is.null(saved_state()))
    before <- length(core$desktop_tables(engine))
    session$setInputs(source = "FILE")
    expect_false(valid_input()); expect_null(original()); expect_length(steps(), 0); expect_null(saved_state())
    expect_match(html(output$result_panel), "データを選択してください")
    expect_identical(output$steps, "[]")
    session$setInputs(publish = 2)
    expect_length(core$desktop_tables(engine), before)
    bad <- tempfile(fileext = ".csv"); writeLines('ID,X\n"broken', bad)
    session$setInputs(file = list(datapath = bad, name = "bad.csv"))
    expect_false(valid_input()); expect_null(original()); expect_identical(phase(), "error")
    expect_match(notice(), "読み込めませんでした")
    expect_match(html(output$result_panel), "ファイルを確認してください")
    session$setInputs(publish = 3)
    expect_length(core$desktop_tables(engine), before)
    session$setInputs(file = list(datapath = file, name = "good.csv"))
    expect_true(valid_input()); expect_length(steps(), 0); expect_equal(nrow(result()$data), 4)
  })
})
test_that("editing a saved name and a rejected resave do not claim the new name was saved", {
  shiny::testServer(core$desktop_prepare_server, args = list(engine = engine), {
    session$setInputs(source = "ADNCA", name = "保存A")
    session$setInputs(publish = 1)
    receipt <- saved_state()
    before <- length(core$desktop_tables(engine))
    expect_match(notice(), "保存しました")
    session$setInputs(name = "保存B")
    expect_match(notice(), "現在の名前では未保存")
    expect_match(html(output$save_status), "現在の名前では未保存")
    expect_identical(saved_state()$id, receipt$id)
    session$setInputs(name = "", publish = 2)
    expect_match(notice(), "保存できません")
    expect_match(html(output$save_status), "現在の名前では未保存")
    expect_length(core$desktop_tables(engine), before)
    expect_identical(saved_state()$name, "保存A")
  })
})
pkapp_close(project)
