source("apps/pk-desktop/tests/nca020_annotation.R")
test_that("MCP annotations audit identity, reject stale revisions and disclose no values", {
  f <- fixture020(); project <- tempfile("annotation-owner-"); dir.create(project)
  on.exit(unlink(project, recursive = TRUE))
  e <- core$desktop_nca_engine(project)
  n <- core$desktop_table_save(e, "TEST NCA", list(source = f$input), list(kind = "nca", specification = f$result$specification), frozen = f$result)
  d <- core$desktop_table_save(e, "TEST DM", list(source = f$dm), list(kind = "prepare", steps = list()))
  v <- core$desktop_table_save(e, "TEST VS", list(source = f$vs), list(kind = "prepare", steps = list()))
  args <- list(result_source = n$id, dm = d$id, vs = v$id, specification = f$spec, name = "TEST background", project_id = e$nca$project_id, base_revision = e$nca$revision, actor = "declared actor", reason = "synthetic check")
  args$specification <- jsonlite::fromJSON(core$desktop_json(args$specification), simplifyVector = FALSE)
  saved <- core$desktop_annotate_nca(e, args)
  expect_equal(saved$counts$result, nrow(f$result$data))
  expect_equal(saved$revision, 2)
  expect_identical(saved$channel, "mcp")
  expect_false(grepl("19\\.5|BASELINE|USUBJID", core$desktop_json(saved)))
  expect_identical(tail(e$nca$audit, 1)[[1]]$operation, "annotate_nca")
  expect_error(core$desktop_annotate_nca(e, args), class = "pkapp_error")
  expect_identical(pkapp_replay(core$desktop_table_path(e, saved$id))$data, core$desktop_table_get(e, saved$id))
  args$base_revision <- e$nca$revision; args$result_source <- d$id
  expect_error(core$desktop_annotate_nca(e, args), "保存済みNCA")
})
test_that("HTTP enforces annotation schema without echoing private content", {
  project <- tempfile("annotation-http-"); dir.create(project); on.exit(unlink(project, recursive = TRUE))
  e <- core$desktop_nca_engine(project); runtime <- core$desktop_r_runtime(e, 3880, 3879, "nca")
  payload <- charToRaw('{"specification":{"version":1,"dm":{"keys":{},"columns":{"SECRET_PRIVATE":"SEX"}}}}')
  response <- core$desktop_http_app(e, runtime)$call(list(REQUEST_METHOD = "POST", PATH_INFO = "/v1/annotate_nca", HTTP_AUTHORIZATION = paste("Bearer", runtime$token),
    HTTP_X_PKAPP_CONTRACT = "pkapp-nca-18", CONTENT_TYPE = "application/json", CONTENT_LENGTH = as.character(length(payload)), rook.input = list(read = function() payload)))
  expect_false(grepl("SECRET_PRIVATE", response$body))
  expect_match(response$body, "E_VALIDATION", fixed = TRUE)
  expect_equal(e$nca$revision, 1)
})
