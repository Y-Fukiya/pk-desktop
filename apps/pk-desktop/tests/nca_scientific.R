source("apps/pk-desktop/pkapp.R")
library(testthat)
core <- environment(pkapp_open)
spec <- list(id = "ID", time = "TIME", concentration = "CONC", concentration_unit = "ng/mL", auc_method = "linear")
change <- function(...) modifyList(spec, list(...), keep.null = TRUE)
values <- function(x) setNames(x$data$AVAL, x$data$PARAMCD)
trapezoids <- function(t, c) sum(diff(t) * (head(c, -1) + tail(c, -1)) / 2)

test_that("missing-only C0 uses the dose reference and preserves observed Tmax", {
  d <- data.frame(ID = "001", TIME = c(-.25,.5,1,2,4,8), CONC = c(0,3,8,6,4,1.5))
  expect_equal(trapezoids(c(0,.5,1,2,4,8), c(0,3,8,6,4,1.5)), 31.5)
  none <- pkapp_nca(d, spec)
  expect_equal(values(none)[c("CMAX", "TMAX")], c(CMAX = 8, TMAX = 1))
  expect_true(is.na(values(none)["AUCLST"]))
  zero <- pkapp_nca(d, change(c0_method = "zero"))
  expect_equal(values(zero), c(CMAX = 8, TMAX = 1, AUCLST = 31.5))
  synthetic <- subset(zero$trace$rows, IMPUTED)
  expect_true(is.na(synthetic$ROW)); expect_equal(synthetic$TIME_H, 0)
  expect_false(synthetic$USE_OBS); expect_true(synthetic$USE_AUC)
  partial <- pkapp_nca(d, change(start = .5))
  expect_equal(values(partial), c(CMAX = 8, TMAX = 1, AUCLST = NA_real_, AUCPART = 30.75))
  expect_match(partial$data$NCA_EXCLUDE[partial$data$PARAMCD == "AUCLST"], "dose reference")
  measured <- rbind(d, data.frame(ID = "001", TIME = 0, CONC = 2))
  kept <- pkapp_nca(measured, change(c0_method = "zero"))
  expect_equal(values(kept)["AUCLST"], c(AUCLST = 32))
  expect_false(any(kept$trace$rows$IMPUTED))
  expect_equal(kept$trace$rows$CONC_USED[kept$trace$rows$TIME_H == 0], 2)
})

test_that("canonical AUCLST terminates before substituted trailing BLQ", {
  d <- data.frame(ID = "001", TIME = c(0,1,2,4), CONC = c(0,8,4,.1), BLQ = c(1,0,0,1))
  result <- pkapp_nca(d, change(blq_column = "BLQ", blq = "as_recorded", include_aucproc = TRUE))
  expect_equal(values(result), c(CMAX = 8, TMAX = 1, AUCLST = 10, AUCPROC = 14.1))
  expect_equal(result$data$TLAST_QUANT_H, rep(2, 4))
  expect_equal(result$data$AUC_LAST_H, rep(2, 4))
  expect_equal(result$data$PROC_LAST_H, rep(4, 4))
  expect_false(result$trace$rows$USE_AUC[4]); expect_true(result$trace$rows$USE_AUCPROC[4])
  expect_length(result$warnings, 0)
  d <- rbind(d, data.frame(ID = "001", TIME = 24, CONC = .1, BLQ = 1))
  expect_equal(values(pkapp_nca(d, change(blq_column = "BLQ", blq = "as_recorded")))["AUCLST"], c(AUCLST = 10))
})

test_that("position-specific BLQ rules match a direct PKNCA cleaning oracle", {
  d <- data.frame(ID = "001", TIME = c(0,.5,1,2,4,8,12,24), CONC = c("BLQ","BLQ","8","BLQ","4","1","BLQ","BLQ"), BLQ = c(1,1,0,1,0,0,1,1))
  step <- list(op = "blq_rules", mode = "positional", profile_columns = "ID", concentration = "CONC", blq_column = "BLQ", time = "TIME",
    zero_time = "pre", pre_rule = "zero", first_rule = "zero", middle_rule = "exclude", last_rule = "exclude", lloq_value = .2)
  prepared <- pkapp_prepare(d, list(step))
  expect_identical(prepared$data[names(d)], d)
  expect_equal(prepared$data$NCA_BLQ_POSITION, c("pre","first","not_blq","middle","not_blq","not_blq","last","last"))
  expect_equal(prepared$data$NCA_MDV, c(0,0,0,1,0,0,1,1))
  options <- list(conc.blq = list(first = 0, middle = "drop", last = "drop"))
  clean <- PKNCA::clean.conc.blq(c(0,0,8,0,4,1,0,0), d$TIME, options = options)
  expect_equal(trapezoids(clean$time, clean$conc), 30)
  result <- pkapp_nca(prepared$data, change(concentration = "NCA_CONC", blq_column = "NCA_BLQ", mdv_column = "NCA_MDV", blq = "as_recorded"))
  expect_equal(values(result)["AUCLST"], c(AUCLST = 30))
  expect_equal(result$data$TLAST_QUANT_H, rep(8, 3))
  expect_equal(result$trace$rows$CONC_ORIGINAL, d$CONC)
  expect_true(all(c("POSITION", "RULE", "Freq") %in% names(prepared$trace[[1]]$summary)))
  legacy <- pkapp_prepare(d, list(modifyList(step, list(mode = "legacy", post_rule = "half_lloq"))))
  expected <- trapezoids(c(0,.5,1,2,4,8), c(0,.1,8,.1,4,1))
  expect_equal(expected, 20.2)
  actual <- pkapp_nca(legacy$data, change(concentration = "NCA_CONC", blq_column = "NCA_BLQ", mdv_column = "NCA_MDV", blq = "as_recorded"))
  expect_equal(values(actual)["AUCLST"], c(AUCLST = expected))
  expect_error(pkapp_nca(prepared$data, change(concentration = "NCA_CONC", blq_column = "NCA_BLQ", mdv_column = "NCA_MDV", blq = "zero")), "前処理済み")
  expect_error(pkapp_nca(prepared$data, change(concentration = "NCA_CONC")), "前処理済み")
})

test_that("positional BLQ never crosses interleaved subjects or dosing periods", {
  d <- data.frame(ID = c("A","B","A","A","B","A","A","A"), PERIOD = c(1,1,2,1,1,2,1,2),
    TIME = c(.5,.5,.5,1,1,1,2,2), CONC = c("BLQ","BLQ","BLQ","8","2","BLQ","BLQ","BLQ"), BLQ = c(1,1,1,0,0,1,1,1))
  step <- list(op = "blq_rules", mode = "positional", profile_columns = c("ID", "PERIOD"), concentration = "CONC", blq_column = "BLQ", time = "TIME",
    pre_rule = "zero", first_rule = "zero", middle_rule = "exclude", last_rule = "exclude")
  result <- pkapp_prepare(d, list(step))
  expect_equal(result$data$NCA_BLQ_POSITION, c("first","first","all_blq","not_blq","not_blq","all_blq","last","all_blq"))
  expect_equal(result$data$NCA_CONC[c(3,6,8)], c(0,0,0))
  spec2 <- change(concentration = "NCA_CONC", blq_column = "NCA_BLQ", mdv_column = "NCA_MDV", blq = "as_recorded", groups = "PERIOD", c0_method = "zero")
  nca <- pkapp_nca(result$data, spec2)$data
  expect_true(all(is.na(nca$AVAL[nca$ID == "A" & nca$PERIOD == "2"])))
  expect_error(pkapp_prepare(d, list(modifyList(step, list(profile_columns = character())))), "解析単位")
  expect_error(pkapp_prepare(transform(d, ID = NA), list(step)), "欠測")
})

test_that("repeat-dose origin and predose lookback are explicit and audited", {
  base <- data.frame(ID = "001", TIME = c(-.25,1,2,4,24), CONC = c(2,4,8,4,1))
  s <- change(c0_method = "predose", predose_window_h = .5)
  relative <- pkapp_nca(base, s)
  absolute <- pkapp_nca(transform(base, TIME = TIME + 72), modifyList(s, list(time_origin = 72, start = 72, end = 96)))
  expect_equal(absolute$data$AVAL, relative$data$AVAL)
  expect_equal(values(absolute)["TMAX"], c(TMAX = 2))
  expect_equal(absolute$data$AUC_LAST_H, rep(24, 3))
  expect_equal(absolute$data$NCA_END_H, rep(24, 3))
  expect_equal(absolute$data$INPUT_END_H, rep(96, 3))
  copied <- subset(absolute$trace$rows, IMPUTED)
  expect_equal(copied$SOURCE_ROW, 1); expect_equal(copied$SOURCE_TIME_H, 71.75)
  expect_equal(copied$TIME_H, 0); expect_false(copied$USE_OBS)
  far <- transform(base, TIME = TIME + 72); far$TIME[1] <- 0
  unavailable <- pkapp_nca(far, modifyList(s, list(time_origin = 72, start = 72)))
  expect_true(is.na(values(unavailable)["AUCLST"]))
  expect_match(unavailable$data$NCA_EXCLUDE[3], "lookback")
  expect_error(pkapp_nca(base, change(c0_method = "predose")), "最大遡及")
  duplicate <- rbind(base, base[1, ])
  expect_match(pkapp_nca(duplicate, s)$data$NCA_EXCLUDE[3], "Ambiguous")
  # A large copied predose value never becomes a synthetic Cmax observation.
  high <- base; high$CONC[1] <- 100
  expect_equal(values(pkapp_nca(high, s))[c("CMAX","TMAX")], c(CMAX = 8, TMAX = 2))
})

test_that("invalid or sparse profiles cannot suppress valid subjects", {
  valid <- data.frame(ID = "valid", TIME = c(0,1,2), CONC = c("0","8","4"), BLQ = 0)
  sparse <- data.frame(ID = "sparse", TIME = 1, CONC = "4", BLQ = 0)
  duplicate <- transform(valid, ID = "duplicate", TIME = c(0,1,1))
  invalid <- transform(valid, ID = "invalid", CONC = c("0","bad","2"))
  blq <- transform(valid, ID = "all_blq", CONC = ".1", BLQ = 1)
  result <- pkapp_nca(rbind(valid, sparse, duplicate, invalid, blq), change(blq_column = "BLQ", blq = "as_recorded", c0_method = "zero"))
  expect_equal(result$data$AVAL[result$data$ID == "valid"], c(8,1,10))
  expect_equal(result$data$AVAL[result$data$ID == "sparse"], c(4, 1, NA_real_))
  expect_true(all(is.na(result$data$AVAL[!result$data$ID %in% c("valid", "sparse")])))
  expect_equal(result$counts[["curves"]], 5)
  expect_equal(result$counts[["failed_curves"]], 3)
  expect_true(all(nzchar(result$data$NCA_EXCLUDE[!result$data$ID %in% c("valid", "sparse")])))
  expect_length(result$trace$groups, 5)
  expect_true(any(grepl("invalid_concentration", result$trace$rows$REASON)))
  one <- pkapp_nca(sparse, change(c0_method = "zero"))
  expect_true(all(one$data$PROFILE_STATUS == "partial"))
  expect_false(any(one$trace$rows$USE_AUC))
  ids <- valid; names(ids)[1] <- "ROW"
  collision <- pkapp_nca(ids, modifyList(spec, list(id = "ROW")))
  expect_true(all(c("SOURCE_ROW", "ROW") %in% names(collision$trace$rows)))
  expect_false(anyDuplicated(names(collision$trace$rows)) > 0)
})

test_that("declared Y blank flags and excluded-row missing BLQ are supported", {
  d <- data.frame(ID = "001", TIME = c(0,1,2,3), CONC = c("BLQ","8","4","ignored"), BLQ = c("Y","","", ""), MDV = c("","","","Y"), PRE = c("Y","","", ""))
  step <- list(op = "blq_rules", concentration = "CONC", time = "TIME", blq_column = "BLQ", mdv_column = "MDV", predose_column = "PRE", pre_rule = "zero", post_rule = "exclude", flag_convention = "y_blank")
  prepared <- pkapp_prepare(d, list(step))
  expect_equal(prepared$data$NCA_CONC, c(0,8,4,NA_real_))
  expect_equal(prepared$data$NCA_MDV, c(0,0,0,1))
  expect_error(pkapp_prepare(d, list(modifyList(step, list(flag_convention = "strict")))), "flag")
  result <- pkapp_nca(d, change(blq_column = "BLQ", mdv_column = "MDV", blq = "zero", flag_convention = "y_blank"))
  expect_equal(values(result), c(CMAX = 8,TMAX = 1,AUCLST = 10))
  strict <- transform(d, BLQ = c("1","0","0",""), MDV = c("0","0","0","1"))
  expect_equal(values(pkapp_nca(strict, change(blq_column = "BLQ", mdv_column = "MDV", blq = "zero"))), values(result))
  # Excluded marked rows retain their original explicit BLQ marker in the audit.
  strict$BLQ[4] <- "1"
  expect_true(pkapp_nca(strict, change(blq_column = "BLQ", mdv_column = "MDV", blq = "zero"))$trace$rows$BLQ[4])
})

test_that("minute datetimes and malformed rows carry independent precision and offset audit", {
  d <- data.frame(SAMPLE = c("2026-11-09T10:00","2026-11-09T11:00Z","2026-11-09","2026-02-30T10:00","2026-11-09T10:00:00.5+09:00"), DOSE = "2026-11-09T09:00+09:00")
  step <- list(op = "elapsed_time", sample_column = "SAMPLE", dose_column = "DOSE", utc_offset = "+09:00")
  result <- pkapp_prepare(d, list(step))
  expect_equal(result$data$NCA_TIME_H, c(1,11,NA,NA,1+.5/3600))
  expect_identical(result$data[names(d)], d)
  rows <- result$trace[[1]]$rows
  expect_equal(rows$SAMPLE_OFFSET_ASSUMED, c(TRUE,FALSE,FALSE,FALSE,FALSE))
  expect_false(any(rows$DOSE_OFFSET_ASSUMED))
  expect_equal(rows$SAMPLE_PRECISION[c(1,2,5)], c("minute_seconds_zero","minute_seconds_zero","fractional_seconds"))
  expect_equal(rows$SAMPLE_REASON[3:4], c("invalid_format","invalid_datetime"))
  expect_error(pkapp_prepare(d, list(modifyList(step, list(invalid_datetime = "error")))), "行 3, 4")
  dst <- data.frame(SAMPLE = "2024-11-03T01:30-05:00", DOSE = "2024-11-03T01:30-04:00")
  withr::local_envvar(TZ = "Europe/London")
  expect_equal(pkapp_prepare(dst, list(step))$data$NCA_TIME_H, 1)
})

test_that("numeric epochs are explicit and POSIXct input remains absolute", {
  d <- data.frame(SAMPLE = c(3600,7200), DOSE = c(0,3600))
  step <- list(op = "elapsed_time", sample_column = "SAMPLE", dose_column = "DOSE", utc_offset = "+09:00", sample_datetime_type = "sas_seconds", dose_datetime_type = "sas_seconds")
  sas <- pkapp_prepare(d, list(step))
  expect_equal(sas$data$NCA_TIME_H, c(1,1))
  expect_equal(sas$trace[[1]]$rows$DOSE_UTC_SECONDS[1], as.numeric(as.Date("1960-01-01"))*86400-9*3600)
  expect_true(all(sas$trace[[1]]$rows$SAMPLE_OFFSET_ASSUMED))
  unix <- pkapp_prepare(d, list(modifyList(step, list(sample_datetime_type = "unix_seconds", dose_datetime_type = "unix_seconds"))))
  expect_equal(unix$trace[[1]]$rows$DOSE_UTC_SECONDS[1], 0)
  expect_false(any(unix$trace[[1]]$rows$SAMPLE_OFFSET_ASSUMED))
  ambiguous <- pkapp_prepare(d, list(modifyList(step, list(sample_datetime_type = "iso", dose_datetime_type = "iso"))))
  expect_true(all(is.na(ambiguous$data$NCA_TIME_H)))
  posix <- data.frame(SAMPLE = as.POSIXct("2026-11-09 10:00:00", tz = "Asia/Tokyo") + c(0,3600), DOSE = as.POSIXct("2026-11-09 09:00:00", tz = "Asia/Tokyo"))
  path <- tempfile(fileext = ".rds"); saveRDS(posix, path)
  result <- pkapp_prepare(pkapp_read_table(path), list(modifyList(step, list(sample_datetime_type = "iso", dose_datetime_type = "iso"))))
  expect_equal(result$data$NCA_TIME_H, c(1,2))
  expect_identical(result$data[names(posix)], posix)
  expect_true(all(result$trace[[1]]$rows$SAMPLE_TYPE == "POSIXct"))
  expect_false(any(result$trace[[1]]$rows$SAMPLE_OFFSET_ASSUMED))
})

test_that("new positional and C0 recipes replay with original inputs and trace", {
  d <- data.frame(ID = "001", TIME = c(-.25,.5,1,2,4,8,12), CONC = c("BLQ","3","8","6","4","1.5","BLQ"), BLQ = c(1,0,0,0,0,0,1))
  step <- list(op = "blq_rules", mode = "positional", profile_columns = "ID", concentration = "CONC", time = "TIME", blq_column = "BLQ",
    pre_rule = "zero", first_rule = "zero", middle_rule = "exclude", last_rule = "half_lloq", lloq_value = .2)
  path <- tempfile("nca-scientific-replay-"); dir.create(path)
  engine <- core$desktop_nca_engine(path)
  saved <- core$desktop_table_save(engine, "準備", list(source = d), list(kind = "prepare", steps = list(step)))
  folder <- core$desktop_table_path(engine, saved$id)
  prepared <- pkapp_replay(folder)$data
  expect_identical(prepared[names(d)], d)
  settings <- change(concentration = "NCA_CONC", blq_column = "NCA_BLQ", mdv_column = "NCA_MDV", blq = "as_recorded",
    c0_method = "predose", predose_window_h = .5, include_aucproc = TRUE)
  options <- PKNCA::PKNCA.options()
  saved_nca <- core$desktop_table_save(engine, "NCA", list(source = prepared), list(kind = "nca", specification = settings))
  nca_folder <- core$desktop_table_path(engine, saved_nca$id)
  replayed <- pkapp_replay(nca_folder)
  expect_identical(replayed$data, core$desktop_table_get(engine, saved_nca$id))
  expect_equal(values(replayed)["AUCLST"], c(AUCLST = 31.5))
  expect_equal(values(replayed)["AUCPROC"], c(AUCPROC = 34.7))
  synthetic <- subset(replayed$trace$rows, IMPUTED)
  expect_equal(synthetic$SOURCE_ROW, 1)
  expect_true(synthetic$BLQ); expect_false(synthetic$QUANTIFIABLE)
  expect_equal(synthetic$CONC_ORIGINAL, "BLQ")
  expect_equal(synthetic$CONC_USED, 0)
  expect_identical(PKNCA::PKNCA.options(), options)
  saved_rows <- pkapp_read_table(file.path(nca_folder, "row_handling.csv"))
  expect_equal(nrow(saved_rows), nrow(d) + 1L)
  expect_equal(saved_rows$CONC_ORIGINAL[1], "BLQ")
  expect_equal(core$desktop_read(file.path(nca_folder, "recipe.json"))$specification$c0_method, "predose")
})
