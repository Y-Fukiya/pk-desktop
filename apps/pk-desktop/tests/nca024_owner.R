test_that("preparation and NCA use immutable snapshots with counts-only disclosure and exact replay", {
  f <- fixture024(); project <- tempfile("nca024-owner-"); dir.create(project); on.exit(unlink(project, recursive = TRUE))
  e <- core$desktop_nca_engine(project)
  source <- core$desktop_table_save(e, "synthetic", list(source = f$data), list(kind = "prepare", steps = list()))
  vs <- core$desktop_table_save(e, "synthetic VS", list(source = f$vs), list(kind = "prepare", steps = list()))
  context <- function() list(project_id = e$nca$project_id, base_revision = e$nca$revision, actor = "test", reason = "synthetic test")
  args <- c(context(), list(source = source$id, vs = vs$id, specification = f$prep, name = "synthetic enriched"))
  args$specification <- jsonlite::fromJSON(core$desktop_json(args$specification), simplifyVector = FALSE)
  saved <- core$desktop_prepare_nca_covariates(e, args)
  expect_equal(saved$counts$result, nrow(f$data))
  expect_false(grepl("ORAL|BASELINE|WEIGHT|original_value|canonical_unit", core$desktop_json(saved)))
  expect_error(core$desktop_prepare_nca_covariates(e, args), class = "pkapp_error")
  expect_identical(pkapp_replay(core$desktop_table_path(e, saved$id))$data, core$desktop_table_get(e, saved$id))
  state <- core$desktop_nca_configure(e, c(context(), list(source = saved$id, specification = f$spec)))
  snapshot <- core$desktop_nca_begin_run(e, context(), "mcp")
  result <- core$desktop_nca_publish(e, snapshot, pkapp_nca(snapshot$data, snapshot$state$specification))
  expect_equal(length(result$parameters), 16)
  expect_true(all(vapply(result$parameters, function(x) is.null(x$mean) && is.null(x$min) && is.null(x$max), logical(1))))
  expect_false(grepl('"(dose_mg|original_value|source_row|records|trace)"', core$desktop_json(result)))
  core$desktop_nca_set_disclosure(e, result$result_id, TRUE, "ui")
  expect_true(core$desktop_nca_disclosure(e, result$result_id)$allowed)
  recorded <- core$desktop_nca_dispatch(e, "nca_save_result", c(context(), list(result_id = result$result_id, name = "synthetic derived")))
  expect_identical(pkapp_replay(core$desktop_table_path(e, recorded$id))$data, e$nca_result$value$data)
  changed <- f$spec; changed$body_size$bsa <- list(mode = "mosteller", height = list(value_column = "HT", unit_column = "HT_UNIT"))
  core$desktop_nca_configure(e, c(context(), list(source = saved$id, specification = changed)))
  expect_false(core$desktop_nca_disclosure(e, result$result_id)$allowed)
  expect_false(core$desktop_nca_current(e))
  expect_error(core$desktop_nca_publish(e, snapshot, pkapp_nca(snapshot$data, snapshot$state$specification)), class = "pkapp_error")
  expect_equal(vals024(pkapp_nca(snapshot$data, snapshot$state$specification), "CLFOBSA"), .5, tolerance = 1e-11)
})

test_that("HTTP validates pre-NCA schema and keeps patient values out of errors", {
  project <- tempfile("nca024-http-"); dir.create(project); on.exit(unlink(project, recursive = TRUE))
  e <- core$desktop_nca_engine(project); runtime <- core$desktop_r_runtime(e, 3880, 3879, "nca")
  secret <- "PRIVATE_024_DO_NOT_RETURN"
  body <- charToRaw(core$desktop_json(list(specification = list(version = 1, profile = list(id = secret, groups = list()), unknown = secret))))
  response <- core$desktop_http_app(e, runtime)$call(list(REQUEST_METHOD = "POST", PATH_INFO = "/v1/prepare_nca_covariates", HTTP_AUTHORIZATION = paste("Bearer", runtime$token), HTTP_X_PKAPP_CONTRACT = "pkapp-nca-18", CONTENT_TYPE = "application/json", CONTENT_LENGTH = as.character(length(body)), rook.input = list(read = function() body)))
  expect_match(response$body, "E_VALIDATION", fixed = TRUE)
  expect_false(grepl(secret, response$body, fixed = TRUE))
  expect_equal(e$nca$revision, 1)
})
