test_that("standalone starts empty and computes only after explicit run", {
  engine <- new_engine()
  expect_null(engine$data)
  expect_false(file.exists(file.path(engine$project, "state.json")))
  shiny::testServer(core$desktop_nca_server, args = list(engine = engine), {
    session$setInputs(source = "FILE")
    expect_null(result())
    session$setInputs(run = 1, save = 1)
    nca_wait_for_job(engine, session)
    expect_null(result())
    expect_length(core$desktop_tables(engine), 0)
    configure(session)
    expect_null(result())
    expect_equal(nrow(source_data()), 8)
    nca_confirm_displayed(session, input, output)
    session$setInputs(run = 2)
    nca_wait_for_job(engine, session)
    expect_equal(result()$value$data$AVAL, c(8, 1, 16, 16, 1, 32))
    expect_null(saved())
    expect_length(core$desktop_tables(engine), 1)
    expect_identical(core$desktop_table_get(engine, engine$nca$source), source_data())
  })
})

test_that("current results download and persist while changed conditions block stale output", {
  engine <- new_engine()
  shiny::testServer(core$desktop_nca_server, args = list(engine = engine), {
    configure(session)
    nca_confirm_displayed(session, input, output)
    session$setInputs(run = 1)
    nca_wait_for_job(engine, session)
    exported <- pkapp_read_table(output$download, format = "csv")
    expect_identical(exported$ID, rep(c("001", "002"), each = 3L))
    expect_equal(as.numeric(exported$AVAL), c(8, 1, 16, 16, 1, 32))
    audit <- pkapp_read_table(output$audit_download, format = "csv")
    expect_equal(nrow(audit), 8)
    expect_true(all(audit$STATUS == "used"))
    settings <- core$desktop_read(output$settings_download)
    expect_identical(settings$specification$auc_method, "linear")
    session$setInputs(save = 1)
    expect_false(is.null(saved()))
    expect_identical(core$desktop_table_get(engine, saved()$id), result()$value$data)
    session$setInputs(auc_method = "lin up/log down")
    expect_null(result())
    session$setInputs(save = 2)
    expect_length(core$desktop_tables(engine), 2)
    expect_match(notice(), "再実行")
    nca_confirm_displayed(session, input, output)
    session$setInputs(run = 2)
    nca_wait_for_job(engine, session)
    expect_false(is.null(result()))
    expect_lt(result()$value$data$AVAL[3], 16)
    session$setInputs(concentration = "missing")
    nca_confirm_displayed(session, input, output)
    session$setInputs(run = 3)
    nca_wait_for_job(engine, session)
    expect_null(result())
    expect_match(notice(), "計算できません")
    session$setInputs(save = 3)
    expect_length(core$desktop_tables(engine), 2)
  })
})

test_that("standalone shell authenticates without sample data or running jobs", {
  engine <- new_engine()
  app <- core$desktop_nca_app(engine, "nca-test-token")
  html <- app$httpHandler(list(REQUEST_METHOD = "GET", PATH_INFO = "/", QUERY_STRING = "token=nca-test-token"))
  expect_equal(html$status, 200L)
  expect_match(html$content, "nca-run_action", fixed = TRUE)
  expect_match(html$content, core$desktop_version, fixed = TRUE)
  server <- app$serverFuncSource()
  for (query in c("", "?token=wrong", "?token=nca-test-token")) {
    session <- shiny::MockShinySession$new()
    session$clientData <- shiny::reactiveValues(url_search = query)
    shiny::withReactiveDomain(session, server(session$input, session$output, session))
    expect_identical(session$isClosed(), query != "?token=nca-test-token")
    session$close()
  }
  expect_null(engine$data)
  expect_length(core$desktop_tables(engine), 0)
})

test_that("NCA launch wrapper passes the mode once and needs no bundle", {
  if (Sys.info()[["sysname"]] != "Darwin") skip("macOS launch wrapper")
  mock <- tempfile("nca-rscript-")
  writeLines(c("#!/bin/sh", "printf '%s\\n' \"$@\""), mock)
  Sys.chmod(mock, "0700")
  output <- withr::with_envvar(c(PK_RSCRIPT = mock, PK_DESKTOP_NO_PAUSE = "1"),
    system2("/bin/bash", c("apps/pk-desktop/launch_nca_macos.command", "--no-browser"), stdout = TRUE, stderr = TRUE))
  expect_equal(sum(output == "--mode"), 1)
  expect_equal(sum(output == "nca"), 1)
  expect_true("--no-browser" %in% output)
  expect_false("--bundle" %in% output)
})

test_that("plot and wide summary distinguish originals replacements and C0 without changing results", {
  d <- data.frame(PROFILE = "001", PERIOD = "A", TIME = c(-.25, .5, 1, 2, 4),
    CONC = c("0", "3", "8", "4", "<0.2"), BLQ = c(1,0,0,0,1), UNIT = "ng/mL")
  p <- pkapp_prepare(d, list(list(op = "blq_rules", mode = "positional", profile_columns = list("PROFILE", "PERIOD"),
    concentration = "CONC", blq_column = "BLQ", time = "TIME", zero_time = "pre",
    pre_rule = "zero", first_rule = "zero", middle_rule = "exclude", last_rule = "half_lloq", lloq_value = .2)))$data
  value <- pkapp_nca(p, list(id = "PROFILE", groups = list("PERIOD"), time = "TIME", concentration = "NCA_CONC",
    unit_column = "UNIT", blq_column = "NCA_BLQ", mdv_column = "NCA_MDV", blq = "as_recorded", c0_method = "zero", auc_method = "linear"))
  original <- value
  wide <- core$desktop_nca_summary(value)
  expect_equal(wide$SOURCE_PROFILE, "001")
  expect_equal(wide$PERIOD, "A")
  expect_equal(wide$AUCLST, 9.5)
  expect_equal(wide$TLAST_QUANT_H, 2)
  named_like_parameter <- data.frame(CMAX = "001", TIME = c(0, 1, 2), CONC = c(0, 8, 4))
  collision <- pkapp_nca(named_like_parameter, list(id = "CMAX", time = "TIME", concentration = "CONC", concentration_unit = "ng/mL", auc_method = "linear"))
  expect_equal(core$desktop_nca_summary(collision)$SOURCE_CMAX, "001")
  expect_equal(core$desktop_nca_summary(collision)$CMAX, 8)
  plotted <- core$desktop_nca_plot_data(value, 1)
  expect_equal(plotted$PLOT_KIND[plotted$IMPUTED], "c0")
  expect_equal(plotted$PLOT_CONC[plotted$TIME_H == 4], .1)
  expect_true(is.na(plotted$PLOT_ORIGINAL[plotted$TIME_H == 4]))
  expect_false(plotted$USE_AUC[plotted$TIME_H == 4])
  expect_identical(value, original)
  failed <- pkapp_nca(d[1, ], list(id = "PROFILE", time = "TIME", concentration = "CONC", unit_column = "UNIT"))
  expect_equal(core$desktop_nca_summary(failed)$PROFILE_STATUS, "excluded")
  all_blq <- transform(d, BLQ = 1, CONC = "<LLOQ>")
  none <- pkapp_nca(all_blq, list(id = "PROFILE", time = "TIME", concentration = "CONC", unit_column = "UNIT", blq_column = "BLQ"))
  expect_false(any(core$desktop_nca_plot_data(none, 1)$PLOT_VALID))
})

test_that("NCA UI protects prepared mapping and new conditions invalidate stale results", {
  p <- pkapp_prepare(transform(fixture, BLQ = 0L), list(list(op = "blq_rules", mode = "positional",
    profile_columns = list("ID"), concentration = "CONC", blq_column = "BLQ", time = "TIME",
    zero_time = "pre", pre_rule = "zero", first_rule = "zero", middle_rule = "exclude", last_rule = "exclude")))$data
  path <- tempfile(fileext = ".csv"); core$pk_write_csv(p, path)
  shiny::testServer(core$desktop_nca_server, args = list(engine = new_engine()), {
    configure(session)
    session$setInputs(file = list(datapath = path, name = "prepared.csv"), concentration = "NCA_CONC", blq_column = "", mdv_column = "", blq = "zero", c0_method = "zero", time_origin = 0)
    nca_confirm_displayed(session, input, output)
    session$setInputs(run = 1)
      nca_wait_for_job(engine, session)
    expect_identical(specification()$blq, "as_recorded")
    expect_identical(specification()$blq_column, "NCA_BLQ")
    expect_identical(specification()$mdv_column, "NCA_MDV")
    expect_null(output$blq_controls)
    expect_false(is.null(result()))
    expect_match(output$profile_selector$html, "ID=001")
    expect_match(output$wide_table$html, "TLAST_QUANT_H")
    expect_match(output$plot_note$html, "最終定量時点")
    session$setInputs(c0_method = "none")
    expect_null(result())
    expect_match(output$actions$html, "disabled")
    nca_confirm_displayed(session, input, output)
    session$setInputs(run = 2)
    nca_wait_for_job(engine, session)
    session$setInputs(include_aucproc = TRUE)
    expect_null(result())
    nca_confirm_displayed(session, input, output)
    session$setInputs(run = 3)
    nca_wait_for_job(engine, session)
    expect_true("AUCPROC" %in% result()$value$data$PARAMCD)
  })
})

